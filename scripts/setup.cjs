#!/usr/bin/env node

// Usage: setup-servicenow-react [--spec <npm spec>] [--pm npm|pnpm|yarn] [--skip-patch]
//
// 1. Writes a tiny local shim package (./react-shim) that re-exports this package,
//    which bundles React 19 + react-dom + the ui-core renderer.
// 2. Points "react", "react-dom" and "@servicenow/ui-renderer-react" at that shim
//    (file:react-shim for npm, link:react-shim for pnpm/yarn: both symlink, so the
//    project has exactly one React: the bundled React 19).
//    - "@servicenow/ui-renderer-react" must exist under that exact name: the ServiceNow
//      JSX babel plugin only treats files as React when it is a dependency.
//    - "react"/"react-dom" must not be the real packages: on an instance they deploy as
//      shared assets that lose to the platform's React 16 on the same page.
// 3. Migrates older setups (v1 copied files in src/node_modules; npm-alias setups).
// 4. Patches the ServiceNow CLI babel preset (JSX -> React 19 createElement).

const fs = require('fs');
const path = require('path');
const BabelPatcher = require('./babel-patcher.cjs');

const OWN = require('../package.json');
const SHIM_DIR = 'react-shim';
const SHIM_NAME = '@quixomatic/react-shim';
const SHIMMED = ['@servicenow/ui-renderer-react', 'react', 'react-dom'];
const LEGACY_DIR = path.join('src', 'node_modules', '@servicenow', 'ui-renderer-react');

// Version of React bundled in dist/index.js (written by scripts/build.mjs). The shim
// carries it so libraries' "react" peer ranges are satisfied.
function bundledReactVersion() {
	try { return require('../dist/meta.json').react; } catch (error) { return '19.0.0'; }
}

// npm symlinks file: folders; pnpm and yarn copy them, so they need link: instead.
function detectPackageManager(cwd, forced) {
	if (forced) return forced;
	if (fs.existsSync(path.join(cwd, 'pnpm-lock.yaml'))) return 'pnpm';
	if (fs.existsSync(path.join(cwd, 'yarn.lock'))) return 'yarn';
	if (fs.existsSync(path.join(cwd, 'package-lock.json'))) return 'npm';
	const agent = process.env.npm_config_user_agent || '';
	if (agent.startsWith('pnpm')) return 'pnpm';
	if (agent.startsWith('yarn')) return 'yarn';
	return 'npm';
}

function parseArgs(argv) {
	const [major, minor] = OWN.version.split('.');
	const opts = { spec: `^${major}.${minor}.0`, patch: true, pm: null };
	for (let i = 0; i < argv.length; i++) {
		if (argv[i] === '--spec') opts.spec = argv[++i];
		else if (argv[i] === '--skip-patch') opts.patch = false;
		else if (argv[i] === '--pm') opts.pm = argv[++i];
	}
	return opts;
}

const MODERN_SASS = '^1.108.2';

// true when the lowest version a range allows is below [major, minor].
function versionBelow(range, [major, minor]) {
	const match = /(\d+)\.(\d+)/.exec(range || '');
	if (!match) return false;
	const [maj, min] = [Number(match[1]), Number(match[2])];
	return maj < major || (maj === major && min < minor);
}

function detectIndent(text) {
	const match = /^([ \t]+)"/m.exec(text);
	return match ? match[1] : 2;
}

function writeShim(cwd) {
	const dir = path.join(cwd, SHIM_DIR);
	const pkgPath = path.join(dir, 'package.json');
	if (fs.existsSync(pkgPath)) {
		const existing = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
		if (existing.name !== SHIM_NAME) throw new Error(`${SHIM_DIR}/ exists and is not the React shim (${existing.name}); move it and re-run.`);
	}
	fs.mkdirSync(dir, { recursive: true });
	// Every subpath (react-dom/client, react/jsx-runtime, ...) re-exports the same module:
	// the bundle exports the union of those APIs. Real files per subpath (not only an
	// "exports" map) so bundlers that ignore "exports", like ServiceNow CLI 27.x, find them.
	const subpaths = { client: 'client.js', 'jsx-runtime': 'jsx-runtime.js', 'jsx-dev-runtime': 'jsx-dev-runtime.js' };
	const shimPkg = {
		name: SHIM_NAME,
		version: bundledReactVersion(),
		private: true,
		description: `Generated by setup-servicenow-react. Makes react, react-dom and @servicenow/ui-renderer-react resolve to ${OWN.name} (React 19 bundled). Commit this folder.`,
		type: 'module',
		main: 'index.js',
		exports: Object.assign(
			{ '.': './index.js' },
			...Object.keys(subpaths).map((key) => ({ [`./${key}`]: `./${subpaths[key]}` })),
			{ './package.json': './package.json' }
		)
	};
	fs.writeFileSync(pkgPath, JSON.stringify(shimPkg, null, 2) + '\n');
	const body = `// Generated by setup-servicenow-react. Do not edit.\nexport * from '${OWN.name}';\nexport { default } from '${OWN.name}';\n`;
	['index.js'].concat(Object.values(subpaths)).forEach((file) => fs.writeFileSync(path.join(dir, file), body));
	console.log(`✅ Wrote ${SHIM_DIR}/ (react, react-dom and @servicenow/ui-renderer-react resolve here)`);
}

// ServiceNow's deploy build compiles every npm package as its own asset and fails on
// pnpm's symlinked store ("Multiple assets emit different content to the same filename").
// A hoisted (npm-style, flat) node_modules works; pnpm is still the package manager.
function ensurePnpmHoisted(cwd) {
	const file = path.join(cwd, 'pnpm-workspace.yaml');
	const existing = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
	const current = /^nodeLinker\s*:\s*(\S+)/m.exec(existing);
	if (current && current[1].replace(/['"]/g, '') === 'hoisted') return;
	if (current) {
		console.log(`⚠️  pnpm-workspace.yaml sets nodeLinker: ${current[1]}. ServiceNow deploys need "nodeLinker: hoisted".`);
		return;
	}
	fs.writeFileSync(file, `nodeLinker: hoisted\n${existing}`);
	console.log('✅ pnpm-workspace.yaml: nodeLinker: hoisted (ServiceNow deploys need a flat node_modules)');
}

// Deploys: by default the CLI ships each npm package as a separate shared asset named only by
// package + version, so packages that publish their API as "exports" subpaths (Base UI,
// @floating-ui/utils/dom, ...) collapse into one asset and most subpaths come back undefined.
// Bundling third-party code into the component avoids that and tree-shakes it. ServiceNow's
// own packages stay platform externals.
const SERVICENOW_PACKAGES = ['@servicenow/*', '@servicenow/**', '@devsnc/*', '@devsnc/**', '@seismic/*', '@seismic/**', '@tectonic/*', '@tectonic/**', 'sn-*', 'sn-*/**'];
const ESM_BUNDLING = {
	build: { allow: ['externals'], deny: ['**'] },
	bundle: { allow: ['**'], deny: SERVICENOW_PACKAGES }
};

function ensureBundledDeploys(cwd) {
	const file = path.join(cwd, 'now-cli.json');
	const raw = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '{}\n';
	const config = JSON.parse(raw);
	config.build = config.build || {};
	config.build.pack = config.build.pack || {};
	const current = config.build.pack.esmExternalModules;
	if (current && JSON.stringify(current) === JSON.stringify(ESM_BUNDLING)) return;
	if (current) {
		console.log('⚠️  now-cli.json already sets build.pack.esmExternalModules; left as is. See the README ("Deploying") for the recommended value.');
		return;
	}
	config.build.pack.esmExternalModules = ESM_BUNDLING;
	fs.writeFileSync(file, JSON.stringify(config, null, detectIndent(raw)) + '\n');
	console.log('✅ now-cli.json: deploys bundle third-party code into the component (ServiceNow packages stay external)');
}

function removeLegacyCopy(cwd) {
	const dir = path.join(cwd, LEGACY_DIR);
	const pkgPath = path.join(dir, 'package.json');
	if (!fs.existsSync(pkgPath)) return;
	try {
		const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
		// Only delete the folder v1 of this package created, never a real package.
		if (/React 18 renderer for ServiceNow UI Framework/.test(pkg.description || '')) {
			fs.rmSync(dir, { recursive: true, force: true });
			// Drop src/node_modules/@servicenow and src/node_modules if v1 left them empty.
			for (const parent of [path.dirname(dir), path.dirname(path.dirname(dir))]) {
				if (fs.existsSync(parent) && fs.readdirSync(parent).length === 0) fs.rmdirSync(parent);
			}
			console.log(`🧹 Removed the old v1 renderer copy: ${LEGACY_DIR}`);
		} else {
			console.log(`ℹ️  Left ${LEGACY_DIR} in place (not created by this package).`);
		}
	} catch (error) {
		console.log(`⚠️  Could not inspect ${LEGACY_DIR}: ${error.message}`);
	}
}

function main() {
	const opts = parseArgs(process.argv.slice(2));
	const cwd = process.cwd();
	const pkgPath = path.join(cwd, 'package.json');

	console.log('🔧 Setting up React 19 for ServiceNow components...');

	if (!fs.existsSync(pkgPath)) {
		console.error('❌ No package.json in the current directory. Run this from your component project root.');
		process.exit(1);
	}

	const raw = fs.readFileSync(pkgPath, 'utf8');
	const pkg = JSON.parse(raw);
	pkg.dependencies = pkg.dependencies || {};
	const deps = pkg.dependencies;
	const pm = detectPackageManager(cwd, opts.pm);
	const shimSpec = `${pm === 'npm' ? 'file' : 'link'}:${SHIM_DIR}`;

	if (deps[SHIMMED[0]] && deps[SHIMMED[0]].startsWith('file:') && deps[SHIMMED[0]].includes('src/node_modules')) removeLegacyCopy(cwd);

	writeShim(cwd);

	const ownBefore = deps[OWN.name];
	if (!ownBefore || opts.spec !== parseArgs([]).spec) deps[OWN.name] = opts.spec;
	console.log(`✅ ${OWN.name} -> ${deps[OWN.name]}`);

	for (const name of SHIMMED) {
		const before = deps[name] || (pkg.devDependencies && pkg.devDependencies[name]);
		if (pkg.devDependencies) delete pkg.devDependencies[name];
		deps[name] = shimSpec;
		console.log(`✅ ${name} -> ${shimSpec}${before && before !== shimSpec ? ` (was ${before})` : ''}`);
	}

	// The CLI compiles styles with the project's `sass` if present (else its own 1.53, which
	// can't parse Tailwind v4 output). Make sure a current one is there.
	pkg.devDependencies = pkg.devDependencies || {};
	const sassBefore = pkg.devDependencies.sass || deps.sass;
	if (!sassBefore || versionBelow(sassBefore, [1, 100])) {
		delete deps.sass;
		pkg.devDependencies.sass = MODERN_SASS;
		console.log(`✅ sass -> ${MODERN_SASS}${sassBefore ? ` (was ${sassBefore}; Tailwind v4 needs a current Sass)` : ''}`);
	}

	// `#/...` -> `./src/...` via package.json "imports" (resolved natively by the CLI's
	// webpack, which ignores jsconfig/tsconfig paths). Use "#/" as the shadcn alias prefix.
	if (!pkg.imports || !pkg.imports['#/*']) {
		pkg.imports = Object.assign({}, pkg.imports, { '#/*': './src/*' });
		console.log('✅ imports: "#/*" -> "./src/*" (use #/components/... in shadcn\'s components.json)');
	}

	fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, detectIndent(raw)) + '\n');
	console.log('✅ Updated package.json');

	if (pm === 'pnpm') ensurePnpmHoisted(cwd);
	ensureBundledDeploys(cwd);

	let patched = true;
	if (opts.patch) {
		console.log('\n🔧 Patching the ServiceNow CLI (babel preset + package exports)...');
		patched = new BabelPatcher().run('patch');
	}

	console.log('');
	if (!patched) {
		console.log('⚠️  package.json is set up, but the ServiceNow CLI could not be patched.');
		console.log('   Install the ui-component extension, then run: npx patch-servicenow-babel');
	}
	console.log('Next steps:');
	console.log(`  1. ${pm} install`);
	console.log(`  2. Commit ${SHIM_DIR}/ with your project`);
	console.log('  3. snc ui-component develop');
	console.log('');
	console.log('Using shadcn/ui? After every `shadcn add`, run: npx servicenow-shadcn-fix');
	console.log('');
	console.log('In your component:');
	console.log('  import { createCustomElement } from "@servicenow/ui-core";');
	console.log('  import react from "@servicenow/ui-renderer-react";');
	console.log('  createCustomElement("my-component", { renderer: { type: react }, view: MyReactView });');
}

try {
	main();
} catch (error) {
	console.error('❌ Setup failed:', error.message);
	process.exit(1);
}
